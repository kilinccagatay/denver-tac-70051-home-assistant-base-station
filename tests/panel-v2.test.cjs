const assert=require('node:assert/strict');
const C=require('../examples/panel-v2/core.js');
const e=(state,attributes={})=>({state,attributes});
let old=e('on',{brightness:100,supported_color_modes:['xy']});
assert.deepEqual(C.merge(old,undefined,{brightness:120}),e('on',{brightness:120,supported_color_modes:['xy']}));
assert.equal(old.attributes.brightness,100,'merging must not mutate previous cache');
assert.equal(C.group(['a','b'],{a:e('on'),b:e('off')}).service,'turn_off');
assert.equal(C.group(['a','b'],{a:e('off'),b:e('off')}).service,'turn_on');
assert.equal(C.group(['a','b'],{a:e('unavailable'),b:e('unknown')}).ready,0);
assert.equal(C.capabilities(e('off',{supported_color_modes:['brightness']})).temperature,false);
assert.equal(C.capabilities(e('off',{supported_color_modes:['xy']})).rgb,true);
assert.equal(C.capabilities(e('off',{supported_color_modes:['onoff']})).dim,false);
assert.equal(C.capabilities(e('off',{supported_color_modes:['color_temp'],max_mireds:500,min_mireds:153})).min,2000);
assert.equal(C.robot(e('cleaning')).service,'return_to_base');
assert.equal(C.robot(e('paused')).service,'return_to_base');
assert.equal(C.robot(e('returning')).service,null);
assert.equal(C.robot(e('unavailable')).service,null);
assert.equal(C.robot(e('docked')).service,'start');
assert.equal(C.robot(e('docked')).label,'Evi Temizle');
assert.equal(C.robot(e('cleaning')).label,'Temizliği Durdur');
assert.equal(C.timeLabel(60),'01:00');assert.equal(C.timeLabel(9),'00:09');
let start='2026-10-30T10:00:00Z';
assert.equal(C.remaining(e('on',{last_triggered:start}),Date.parse(start)+15000),45);
assert.equal(C.remaining(e('off',{last_triggered:start}),Date.parse(start)),null);
assert.equal(C.remaining(e('on',{last_triggered:start}),Date.parse(start)+90000),0);
let handlers={},pending,short=0,long=0;
let target={addEventListener:(n,fn)=>handlers[n]=fn};
let scheduler={set:fn=>(pending=fn,1),clear:()=>{pending=null},now:()=>10000};
C.bindPress(target,()=>short++,()=>long++,scheduler);
const ev=(type,extra={})=>Object.assign({type,clientX:0,clientY:0,button:0,preventDefault(){},stopPropagation(){}},extra);
handlers.mousedown(ev('mousedown'));handlers.mouseup(ev('mouseup'));handlers.click(ev('click'));
assert.equal(short,1);assert.equal(long,0);
handlers.mousedown(ev('mousedown'));pending();handlers.mouseup(ev('mouseup'));handlers.click(ev('click'));
assert.equal(short,1,'long press must not also toggle');assert.equal(long,1);
handlers.touchstart(ev('touchstart',{touches:[{clientX:0,clientY:0}]}));
handlers.touchmove(ev('touchmove',{touches:[{clientX:25,clientY:0}]}));handlers.touchend(ev('touchend'));handlers.click(ev('click'));
assert.equal(short,1,'drag must not toggle or open dialog');assert.equal(long,1);
const features=8192|4|16;
assert.equal(C.robotControl(e('cleaning',{supported_features:features}),'start').service,null);
assert.equal(C.robotControl(e('cleaning',{supported_features:features}),'pause').service,'pause');
assert.equal(C.robotControl(e('paused',{supported_features:features}),'pause').service,'start');
assert.equal(C.robotControl(e('idle',{supported_features:features}),'dock').service,'return_to_base');
assert.equal(C.robotControl(e('docked',{supported_features:features}),'dock').service,null);
assert.equal(C.robotControl(e('cleaning',{supported_features:0}),'pause').service,null);
assert.equal(C.robotControl(e('unavailable'),'start').service,null);
let chosenDelay=900,scheduledDelay;
C.bindPress(target,()=>short++,()=>long++,{set:(fn,ms)=>(pending=fn,scheduledDelay=ms,1),clear:()=>{pending=null},now:()=>10000},()=>chosenDelay);
handlers.mousedown(ev('mousedown'));assert.equal(scheduledDelay,900);
handlers.mouseup(ev('mouseup'));chosenDelay=450;
handlers.mousedown(ev('mousedown'));assert.equal(scheduledDelay,450,'changed preference applies to existing buttons');
handlers.mouseup(ev('mouseup'));
console.log('Panel V2: state, capabilities, robot, countdown, and gesture checks passed.');
